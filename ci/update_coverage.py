#!/usr/bin/env python3
"""Regenerate COVERAGE.md from the current build/linker map.

This is a stub until the Stadium Zero build bootstrap exists. Calling it today
reports the documented bootstrap state (no verified function count) rather than
fabricating coverage numbers.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = """<!-- Generated by ci/update_coverage.py. Do not edit by hand. -->

# pokestadium0 decompilation coverage

<!-- AUTO_COVERAGE:START -->
- Functions with C implementations: **0 / 0 (0%)**
- Remaining decompilable `GLOBAL_ASM` owners: **0**
<!-- AUTO_COVERAGE:END -->

This repository is a bootstrap: the Stadium Zero ROM identity, segment layout, and
compiler/toolchain confirmation are still pending. Do not transfer verification from
Stadium 1 or Stadium 2 to Stadium Zero without per-target evidence.

Regenerate with:
`python3 ci/update_coverage.py`
"""


def main() -> int:
    out = ROOT / "COVERAGE.md"
    out.write_text(TEMPLATE, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
