#!/usr/bin/env python3
"""Regenerate COVERAGE.md for both matching tracks.

The denominator is the first-pass assembly-owner inventory, not a recovered
original function count. The per-function section comes from
docs/function-matches.csv ("C" means the function compiles to the ROM bytes
under tools/check_functions.py). The production section requires a current
full-ROM PASS receipt.
"""
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def production(owners):
    receipt = json.loads((ROOT / 'docs/production-build-receipt.json').read_text())
    registry = ROOT / 'config/jp/matching.json'
    accepted = json.loads(registry.read_text())
    if (receipt.get('status') != 'PASS' or not receipt['full_rom_identical']
            or receipt['input_sha256'] != receipt['output_sha256']
            or receipt['matching_registry_sha256'] != digest(registry)):
        raise ValueError('coverage requires a current full-ROM PASS receipt')
    for path, expected in {**receipt['c_sources_sha256'], **receipt['build_tools_sha256']}.items():
        if digest(ROOT / path) != expected:
            raise ValueError('receipt is stale for ' + path + '; rebuild and refresh receipt')
    count = len(accepted)
    if count != receipt['c_owners']:
        raise ValueError('receipt C count differs')
    size = sum(owners[row['name']]['size'] for row in accepted)
    return count, size, receipt['output_sha256']


def main() -> int:
    inventory = json.loads((ROOT / "docs/pragma-inventory.json").read_text())
    owners = {row["name"]: row for row in inventory["owners"]}
    sizes = {name: row["size"] for name, row in owners.items()}
    with (ROOT / "docs/function-matches.csv").open() as handle:
        rows = list(csv.DictReader(handle))
    total = len(sizes)
    total_bytes = sum(sizes.values())
    status = Counter(row["status"] for row in rows)
    c_rows = [row for row in rows if row["status"] in ("s1", "m2c")]
    c_bytes = sum(sizes[row["owner"]] for row in c_rows)
    libultra = [row for row in rows if row["origin"].startswith("libultra:")]
    lib_bytes = sum(sizes[row["owner"]] for row in libultra)
    count, size, rom_sha = production(owners)
    covered = inventory['summary']['covered_text_bytes']
    text = f"""<!-- Generated by ci/update_coverage.py. Do not edit by hand. -->

# pokestadium0 decompilation coverage

## Per-function matching (`src/`)

<!-- AUTO_COVERAGE:START -->
- Assembly owners (first-pass function inventory): **{total:,}** covering **{total_bytes:,}** text bytes
- Functions with matching C: **{len(c_rows):,} / {total:,} ({100 * len(c_rows) / total:.1f}%)**, **{c_bytes:,}** bytes ({100 * c_bytes / total_bytes:.1f}%)
  - ported from the Stadium 1 decomp: **{status['s1']:,}**
  - first-pass m2c output: **{status['m2c']:,}**
- Identified libultra functions (identical to ultralib 2.0I, kept as `GLOBAL_ASM`): **{len(libultra):,}**, **{lib_bytes:,}** bytes
- Remaining `GLOBAL_ASM` owners: **{status['asm'] - len(libultra):,}** (plus the libultra owners above)
<!-- AUTO_COVERAGE:END -->

"Matching C" is a per-function comparison against the retail ROM made by
`tools/check_functions.py`; file-level data and `.rodata` layout of `src/` are
unverified. See [docs/matching.md](docs/matching.md).

## Full-ROM production build (`candidates/`)

- C owners passing the full-ROM gate: **{count:,}/{total:,} ({count / total:.1%})**
- Remaining assembly owners: **{total - count:,}**
- C owner bytes: **{size:,}/{covered:,} ({size / covered:.2%})**
- Complete ROM comparison: **PASS**, SHA-256 `{rom_sha}`

Counts use the conservative first-pass assembly-owner inventory, not confirmed
original functions or translation units. The initial 100 are eight-byte empty
returns. Data, microcode, opaque ranges, and resource-only images are excluded
from the owner-byte denominator. Coverage applies to the explicit production C
registry and the committed validation receipt; original compiler settings remain
under investigation beyond the measured candidates.

See [the production build](docs/production-build.md),
[matching registry](config/jp/matching.json), and
[validation receipt](docs/production-build-receipt.json).

Regenerate with `make coverage` after updating the verified receipt.
"""
    out = ROOT / "COVERAGE.md"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
