#!/usr/bin/env python3
"""Generate conditional C pragma owners from scoped Stadium Zero CPU text.

spimdisasm boundaries are a first-pass inventory, not recovered original TUs.
Cross-boundary non-call flow is conservatively kept in a shared assembly owner.
Assembly is generated locally under ignored asm/, never copied from a donor.
"""
import argparse
from bisect import bisect_right
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import struct

import rabbitizer
import spimdisasm

from map_fragment_sections import load_image
from map_rom import EXPECTED_SHA256

ROOT = Path(__file__).resolve().parents[1]
BANNER = "/* Generated by tools/generate_pragmas.py; first-pass assembly owners. */"
LISTING_WORD = re.compile(r"/\*\s+[0-9A-F]+\s+[0-9A-F]+\s+([0-9A-F]{8})\s*\*/")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def make_section(data, start, end, base, name, ram_end=None, entries=()):
    context = spimdisasm.common.Context()
    context.changeGlobalSegmentRanges(0, len(data), base,
                                      ram_end or base + len(data))
    for entry in sorted(set(entries)):
        if start <= entry < end:
            context.globalSegment.addFunction(base + entry, vromAddress=entry)
    section = spimdisasm.mips.sections.SectionText(
        context, start, end, base + start, name, data, 0, None)
    section.analyze()
    return section


def merge_owners(section, data, base, transfers):
    """Do not split ordinary branch destinations or switch cases into functions.

    Call targets remain separate. Tail jumps to known local call targets also
    remain separate; other non-call edges conservatively share one asm owner.
    """
    functions = section.symbolList
    starts = [function.vromStart for function in functions]
    links = list(range(len(functions)))
    entry_calls = set()
    edges = []
    for position in range(section.vromStart, section.vromEnd, 4):
        value = struct.unpack_from(">I", data, position)[0]
        instruction = rabbitizer.Instruction(value, base + position)
        if instruction.doesLink() and instruction.isJumpWithAddress():
            entry_calls.add(instruction.getInstrIndexAsVram() - base)
        elif instruction.isBranch() and not instruction.doesLink():
            edges.append((position, instruction.getBranchVramGeneric() - base,
                          instruction.isUnconditionalBranch()))
        elif instruction.isJumpWithAddress() and not instruction.doesLink():
            edges.append((position, instruction.getInstrIndexAsVram() - base, True))
    for transfer in transfers:
        if transfer["transfer"] == "jump" and transfer["status"].startswith("resolved_"):
            edges.extend((int(transfer["site"], 0), int(target, 0), False)
                         for target in transfer.get("targets", []))

    def find(index):
        while links[index] != index:
            links[index] = links[links[index]]
            index = links[index]
        return index

    for source, target, tail in edges:
        if tail and target in entry_calls:
            continue
        if not section.vromStart <= source < section.vromEnd \
                or not section.vromStart <= target < section.vromEnd:
            continue
        left, right = sorted((bisect_right(starts, source) - 1,
                              bisect_right(starts, target) - 1))
        if left < 0:
            continue
        for index in range(left, right):
            links[find(index + 1)] = find(index)
    grouped = []
    for index, function in enumerate(functions):
        root = find(index)
        if grouped and grouped[-1][0] == root:
            grouped[-1][1].append(function)
        else:
            grouped.append((root, [function]))
    return [members for _, members in grouped]


def conditional(symbol, assembly):
    return (f"#ifdef NON_MATCHING\n"
            f"/* TODO: decompile {symbol}; signature not recovered. */\n"
            f"#else\n"
            f'#pragma GLOBAL_ASM("{assembly}")\n'
            f"#endif\n")


def generate(rom, mapping, sections, flow):
    if digest(rom) != EXPECTED_SHA256:
        raise ValueError("wrong input ROM")
    spimdisasm.common.GlobalConfig.ASM_GENERATED_BY = True
    spimdisasm.common.GlobalConfig.DISASSEMBLE_UNKNOWN_INSTRUCTIONS = False
    # The default IDO-oriented splitter is a heuristic, not compiler discovery.
    outputs = {}
    units = []
    excluded = []
    slot_counts = Counter(item["link_base"] for item in mapping["fragments"])
    resident_base = 0x80000400 - 0x1000
    # Probe the scoped resident envelope, then discard invalid candidate spans
    # and restart with fresh contexts so their fake calls cannot seed functions.
    probe = make_section(rom, 0x1060, 0x5D8C0, resident_base, "resident",
                         ram_end=0x80105360)
    bad = [(function.vromStart, function.vromEnd)
           for function in probe.symbolList if function.hasUnimplementedIntrs]
    clean = []
    cursor = 0x1060
    for start, stop in bad:
        if cursor < start:
            clean.append((cursor, start))
        excluded.append({"image": "resident", "start": hex(start), "end": hex(stop),
                         "reason": "invalid instruction encodings in first-pass candidate"})
        cursor = stop
    if cursor < 0x5D8C0:
        clean.append((cursor, 0x5D8C0))
    specs = []
    for start, stop in clean:
        specs.append({"owner": "1060", "source": "src/1060.c",
                      "data": rom, "start": start, "end": stop,
                      "base": resident_base, "ram_end": 0x80105360,
                      "image_index": None, "entries": [], "transfers": []})
    for index, (metadata, report, detail) in enumerate(zip(
            mapping["fragments"], sections["images"], flow["images"])):
        if report["text_envelope"] is None:
            continue
        data = load_image(rom, metadata)
        start, stop = [int(value, 0) for value in report["text_envelope"]]
        base = int(metadata["link_base"], 0)
        owner = f"fragments/fragment{index:03d}_{int(metadata['rom_start'], 0):X}"
        entries = [int(metadata["entry_offset"], 0)]
        for transfer in detail["transfers"]:
            if transfer["status"] == "known_initializer_candidates_runtime_unresolved":
                entries.extend(int(target, 0) for target in transfer.get("targets", []))
            elif transfer["status"] == "resolved_inspected_register_protocol" \
                    and int(transfer["site"], 0) == 0x3CD8:
                entries.extend(int(target, 0) for target in transfer["targets"])
        specs.append({"owner": owner, "source": f"src/{owner}.c",
                      "data": data, "start": start, "end": stop, "base": base,
                      "ram_end": base + max(len(data), int(metadata["ram_size"], 0)),
                      "image_index": index, "entries": entries,
                      "transfers": detail["transfers"], "metadata": metadata,
                      "reused_slot": slot_counts[metadata["link_base"]] > 1})
    source_blocks = {}
    owners = []
    for spec in specs:
        section = make_section(spec["data"], spec["start"], spec["end"], spec["base"],
                               spec["owner"], spec["ram_end"], spec["entries"])
        for function in section.symbolList:
            name = f"func_{function.vram:08X}"
            if spec.get("reused_slot"):
                name += f"_{spec['image_index']:03d}"
            function.contextSym.name = name
        for members in merge_owners(section, spec["data"], spec["base"], spec["transfers"]):
            start, stop = members[0].vromStart, members[-1].vromEnd
            symbol = members[0].getName()
            if any(function.hasUnimplementedIntrs for function in members):
                excluded.append({"image": spec["image_index"], "start": hex(start),
                                 "end": hex(stop), "reason": "invalid candidate assembly owner"})
                continue
            assembly = "\n".join(function.disassemble() for function in members)
            listed = b"".join(int(value, 16).to_bytes(4, "big")
                              for value in LISTING_WORD.findall(assembly))
            raw = spec["data"][start:stop]
            if listed != raw:
                raise ValueError(f"assembly listing bytes differ: {spec['owner']} {symbol}")
            asm_path = f"asm/jp/nonmatchings/{spec['owner']}/{symbol}.s"
            # Shared owner may include multiple callable aliases. Preserve all
            # emitted glabels instead of splitting branch/coroutine continuations.
            outputs[asm_path] = assembly.encode()
            source_blocks.setdefault(spec["source"], []).append(conditional(symbol, asm_path))
            row = {"name": symbol, "source": spec["source"], "assembly": asm_path,
                   "image_index": spec["image_index"], "start": hex(start), "end": hex(stop),
                   "link_start": hex(spec["base"] + start),
                   "size": len(raw), "input_sha256": digest(raw),
                   "assembly_sha256": digest(outputs[asm_path]),
                   "aliases": [function.getName() for function in members[1:]],
                   "boundary_status": "first_pass_conservative_assembly_owner"}
            if spec["image_index"] is None:
                row["rom_start"], row["rom_end"] = hex(start), hex(stop)
            elif spec["metadata"]["storage"] == "raw":
                origin = int(spec["metadata"]["rom_start"], 0)
                row["rom_start"], row["rom_end"] = hex(origin + start), hex(origin + stop)
            owners.append(row)
    for source, blocks in source_blocks.items():
        outputs[source] = (BANNER + '\n#include "global.h"\n\n'
                           "/* NON_MATCHING branches are TODO slots, not C implementations. */\n\n"
                           + "\n".join(blocks)).encode()
        units.append({"source": source, "source_sha256": digest(outputs[source]),
                      "pragma_count": len(blocks)})
    inventory = {
        "input_sha256": EXPECTED_SHA256, "spimdisasm_version": spimdisasm.__version__,
        "boundary_status": "first_pass_not_original_function_or_translation_unit_recovery",
        "summary": {"source_files": len(units), "pragma_owners": len(owners),
                    "covered_text_bytes": sum(row["size"] for row in owners),
                    "excluded_ranges": len(excluded),
                    "fragment_images_with_stubs": sum(unit["source"].startswith("src/fragments/")
                                                      for unit in units)},
        "sources": units, "owners": owners, "excluded_ranges": excluded,
    }
    outputs["docs/pragma-inventory.json"] = (json.dumps(inventory, indent=2) + "\n").encode()
    return outputs, inventory


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("rom", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mapping = json.loads((ROOT / "docs/mappings/resident-fragments.json").read_text())
    sections = json.loads((ROOT / "docs/sections/refined/fragment-sections.json").read_text())
    flow = json.loads((ROOT / "docs/sections/refined/flow-validation.json").read_text())
    outputs, inventory = generate(args.rom.read_bytes(), mapping, sections, flow)
    previous = ROOT / "docs/pragma-inventory.json"
    prior = json.loads(previous.read_text()) if previous.exists() else {}
    old_hashes = {row["source"]: row["source_sha256"] for row in prior.get("sources", [])}
    # Validate every source before writing anything; never overwrite human C.
    for path, data in outputs.items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_bytes() != data:
                raise ValueError(f"generated output differs: {path}")
        elif path.startswith("src/") and target.exists():
            old = target.read_bytes()
            if digest(old) != old_hashes.get(path) and old != data:
                raise ValueError(f"refusing to overwrite edited source: {path}")
    if not args.check:
        for path, data in outputs.items():
            target = ROOT / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    print(json.dumps(inventory["summary"], indent=2))


if __name__ == "__main__":
    main()
